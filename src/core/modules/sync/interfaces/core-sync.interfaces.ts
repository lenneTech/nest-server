/**
 * The wire format of the sync protocol (`docs/offline-sync-protocol.md`) and the hook of the `custom` strategy.
 * Types only.
 */

/** A pushed change (protocol §6.2) */
export interface ISyncPushItem {
  /** The version the change is based on; absent only on the item that creates the record */
  baseVersion?: number;
  /** The fields to set (`upsert`); validated against the model's input like any create/update */
  data?: Record<string, unknown>;
  /** For `merge`: the field names the client changed. Without it, every key in `data` counts as changed */
  fields?: string[];
  /** The record's id, in the model's format */
  id: string;
  /** Unique per change, generated by the client; the same change sent again carries the same id */
  mutationId: string;
  op: SyncPushOp;
}

export type SyncPushOp = 'delete' | 'upsert';

/** Protocol §7 */
export type SyncItemStatus = 'applied' | 'conflict' | 'merged' | 'not_found' | 'rejected' | 'retry';

/** Protocol §7 — the reason of a `rejected` item */
export type SyncRejectCode = 'CUSTOM_REFUSED' | 'FORBIDDEN' | 'ID_UNAVAILABLE' | 'INVALID_ID' | 'VALIDATION_FAILED';

/**
 * A record as a pull delivers it (protocol §5.2): a live record carries its content in `data`, a tombstone carries
 * no `data` — only its id, version, times, `tenantId` and the model's scope fields (protocol §2).
 */
export interface ISyncRecord {
  [scopeField: string]: unknown;
  data?: Record<string, unknown>;
  deletedAt: Date | null;
  id: string;
  updatedAt?: Date;
  version: number;
}

/** Protocol §6.6 */
export interface ISyncPushResult {
  code?: SyncRejectCode;
  details?: unknown;
  id: string;
  mutationId: string;
  /** The server's record (`conflict`, `merged`) */
  record?: ISyncRecord;
  status: SyncItemStatus;
  version?: number;
}

/** Protocol §5.2 */
export interface ISyncPullResult {
  cursor: string;
  hasMore: boolean;
  items: ISyncRecord[];
}

/** Protocol §8 */
export type SyncResyncReason = 'access' | 'horizon' | 'invalid';

/** What `resolveSyncConflict()` receives under the `custom` strategy */
export interface ISyncConflictContext {
  /** What the client sent */
  change: { baseVersion?: number; data?: Record<string, unknown>; fields?: string[]; op: SyncPushOp };
  /** The authenticated caller, as the controller received it */
  currentUser: any;
  id: string;
  model: string;
  /** The record as the caller may see it now, a live record (a tombstone always conflicts) */
  server: ISyncRecord;
}

/**
 * The answer of `resolveSyncConflict()`: the fields to write on top of the server's record, a deletion, or a refusal
 * (`rejected` / `CUSTOM_REFUSED`). The write runs through the same pipeline as every push.
 */
export type SyncConflictResolution = { data: Record<string, unknown> } | { delete: true } | { refuse: true };

/** A model service whose model declares `strategy: 'custom'` implements this */
export interface SyncConflictResolver {
  resolveSyncConflict(context: ISyncConflictContext): Promise<SyncConflictResolution> | SyncConflictResolution;
}
