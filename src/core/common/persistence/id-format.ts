import { randomBytes } from 'node:crypto';

import { isObjectIdLike } from '../helpers/id.helper.js';

export { isObjectIdLike } from '../helpers/id.helper.js';

/**
 * The stored id format, the same on every database: 24 hex characters — an ObjectId's hex string.
 * On MongoDB that IS the ObjectId; on SQL the application generates it (plan §3.5), so ids, URLs and
 * validators stay identical across the fleet and survive a data move between databases.
 */
const STORED_ID = /^[0-9a-f]{24}$/i;

/**
 * Whether a value is a well-formed stored id: an ObjectId (from any bson copy) or its 24-character hex
 * string.
 *
 * Deliberately stricter than `Types.ObjectId.isValid()`, which also accepts any 12-character string
 * (a 12-byte ObjectId seed) — no stored id ever has that form. For strings this is exactly the rule
 * `checkStringIds()` and `CoreFileService.isMalformedFileId()` applied as `length === 24 && isValid()`.
 */
export function isWellFormedId(value: unknown): boolean {
  if (typeof value === 'string') {
    return STORED_ID.test(value);
  }
  return isObjectIdLike(value);
}

const PROCESS_UNIQUE = randomBytes(5);
let counter = randomBytes(3).readUIntBE(0, 3);

/**
 * A new id in the stored format, generated by the application (plan §3.5): an ObjectId — 4 bytes of seconds,
 * 5 random bytes per process, a 3-byte counter — so ids stay sortable by creation time like MongoDB's.
 */
export function generateId(): string {
  const bytes = Buffer.alloc(12);
  bytes.writeUInt32BE(Math.floor(Date.now() / 1000) >>> 0, 0);
  PROCESS_UNIQUE.copy(bytes, 4);
  counter = (counter + 1) % 0x1000000;
  bytes.writeUIntBE(counter, 9, 3);
  return bytes.toString('hex');
}

/**
 * A uuidv7 as the framework stores it (plan §3.5): lowercase, hyphenated, version nibble `7`, variant `8`–`b`. The id
 * format a synchronized model may choose instead of the ObjectId (`@PersistedModel({ sync: { idFormat: 'uuidv7' } })`).
 */
const UUID_V7 = /^[0-9a-f]{8}-[0-9a-f]{4}-7[0-9a-f]{3}-[89ab][0-9a-f]{3}-[0-9a-f]{12}$/;

/** Whether a value is a uuidv7 in the stored form — lowercase only, so one id has exactly one spelling */
export function isUuidV7(value: unknown): value is string {
  return typeof value === 'string' && UUID_V7.test(value);
}

/**
 * A new uuidv7 (RFC 9562): 48 bits of milliseconds, then 74 random bits — sortable by creation time like an ObjectId,
 * but with nothing after the timestamp that one observed id would let anybody predict.
 */
export function generateUuidV7(): string {
  const bytes = randomBytes(16);
  const millis = Date.now();
  bytes.writeUIntBE(Math.floor(millis / 0x10000), 0, 4);
  bytes.writeUInt16BE(millis % 0x10000, 4);
  bytes[6] = (bytes[6] & 0x0f) | 0x70;
  bytes[8] = (bytes[8] & 0x3f) | 0x80;
  const hex = bytes.toString('hex');
  return `${hex.slice(0, 8)}-${hex.slice(8, 12)}-${hex.slice(12, 16)}-${hex.slice(16, 20)}-${hex.slice(20)}`;
}
